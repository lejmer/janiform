import argparse
import subprocess
from pathlib import Path
from typing import Final

GENERATED_HEADER: Final[str] = "<!-- This file is generated by scripts/generate_docs_references.py. DO NOT EDIT. -->"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate or validate checked-in documentation reference pages.",
    )

    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with a non-zero status when a generated reference page is out of date.",
    )

    args = parser.parse_args()

    workspace_root = Path(__file__).resolve().parents[1]
    expected_pages = build_expected_pages(workspace_root)

    drifted_paths: list[Path] = []
    for relative_path, expected_content in expected_pages.items():
        path = workspace_root / relative_path
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected_content:
                drifted_paths.append(path)

            continue

        path.write_text(expected_content, encoding="utf-8")

    if args.check:
        if drifted_paths:
            print("Generated documentation reference pages are out of date:")
            for path in drifted_paths:
                print(f"- {path.relative_to(workspace_root)}")

            print("Regenerate them with `python3 scripts/generate_docs_references.py`.")

            return 1

        return 0

    print(f"Generated {len(expected_pages)} documentation reference pages.")

    return 0


def build_expected_pages(workspace_root: Path) -> dict[Path, str]:
    return {
        Path("docs/reference/cli.md"): render_cli_reference_page(workspace_root),
        Path("docs/reference/python-api.md"): render_reference_page("Python API Reference"),
    }


def render_cli_reference_page(workspace_root: Path) -> str:
    result = subprocess.run(
        [
            "cargo",
            "run",
            "--quiet",
            "-p",
            "janiform-cli",
            "--features",
            "docs-reference",
            "--bin",
            "janiform-cli-docs-reference",
        ],
        capture_output=True,
        check=True,
        cwd=workspace_root,
        text=True,
    )

    return f"{GENERATED_HEADER}\n\n{result.stdout}"


def render_reference_page(title: str) -> str:
    return f"{GENERATED_HEADER}\n\n# {title}\n\n"


if __name__ == "__main__":
    raise SystemExit(main())
