import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any, Final

GENERATED_HEADER: Final[str] = "<!-- This file is generated by scripts/generate_docs_references.py. DO NOT EDIT. -->"
PYTHON_SOURCE_DIRECTORY_NAME: Final[str] = "python"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate or validate checked-in documentation reference pages.",
    )

    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with a non-zero status when a generated reference page is out of date.",
    )

    args = parser.parse_args()

    workspace_root = Path(__file__).resolve().parents[1]

    configure_python_import_path(workspace_root)

    expected_pages: dict[Path, str] = build_expected_pages(workspace_root)

    drifted_paths: list[Path] = []
    for relative_path, expected_content in expected_pages.items():
        path = workspace_root / relative_path
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected_content:
                drifted_paths.append(path)

            continue

        path.write_text(expected_content, encoding="utf-8")

    if args.check:
        if drifted_paths:
            print("Generated documentation reference pages are out of date:")
            for path in drifted_paths:
                print(f"- {path.relative_to(workspace_root)}")

            print("Regenerate them with `python3 scripts/generate_docs_references.py`.")

            return 1

        return 0

    print(f"Generated {len(expected_pages)} documentation reference pages.")

    return 0


def build_expected_pages(workspace_root: Path) -> dict[Path, str]:
    return {
        Path("docs/reference/cli.md"): render_cli_reference_page(workspace_root),
        Path("docs/reference/python-api.md"): render_python_api_reference_page(),
    }


def render_cli_reference_page(workspace_root: Path) -> str:
    result = subprocess.run(
        [
            "cargo",
            "run",
            "--quiet",
            "-p",
            "janiform-cli",
            "--features",
            "docs-reference",
            "--bin",
            "janiform-cli-docs-reference",
        ],
        capture_output=True,
        check=True,
        cwd=workspace_root,
        text=True,
    )

    return f"{GENERATED_HEADER}\n\n{result.stdout}"


def configure_python_import_path(workspace_root: Path) -> None:
    for path in (workspace_root, workspace_root / PYTHON_SOURCE_DIRECTORY_NAME):
        path_text = str(path)
        if path_text not in sys.path:
            sys.path.insert(0, path_text)


def render_python_api_reference_page() -> str:
    from tests.support.public_api_contract_guardrails import (
        PUBLIC_CONTRACT_MODULE_NAMES,
        build_public_api_contract_snapshot,
    )

    snapshot = build_public_api_contract_snapshot()

    return "\n".join(
        [
            GENERATED_HEADER,
            "",
            "# Python API Reference",
            "",
            render_python_package_root(snapshot["package_root"]),
            render_python_module_overview(PUBLIC_CONTRACT_MODULE_NAMES),
            *[
                render_python_module(snapshot["public_modules"][module_name])
                for module_name in PUBLIC_CONTRACT_MODULE_NAMES
            ],
            "",
        ]
    )


def render_python_package_root(package_root: dict[str, Any]) -> str:
    exports = ", ".join(code_span(export_name) for export_name in package_root["exports"])

    return "\n".join(
        [
            "## Package Root",
            "",
            f"- Module: {code_span(package_root['module_name'])}",
            f"- Exports: {exports if exports else 'none'}",
            "",
        ]
    )


def render_python_module_overview(module_names: tuple[str, ...]) -> str:
    lines = [
        "## Public Modules",
        "",
        "| Module |",
        "|--------|",
    ]
    for module_name in module_names:
        lines.append(f"| [{code_span(module_name)}](#{anchor_id('python-api-module-' + module_name)}) |")

    lines.append("")

    return "\n".join(lines)


def render_python_module(module: dict[str, Any]) -> str:
    module_name = module["module_name"]
    lines = [
        f'<a id="{anchor_id("python-api-module-" + module_name)}"></a>',
        f"## {code_span(module_name)}",
        "",
    ]

    if module["schema_identifiers"]:
        lines.extend(render_schema_identifiers(module["schema_identifiers"]))

    lines.extend(
        [
            "| Symbol | Kind | Summary |",
            "|--------|------|---------|",
        ]
    )
    for export_name in module["exports"]:
        symbol = module["symbols"][export_name]
        symbol_anchor = anchor_id(f"python-api-symbol-{module_name}-{export_name}")

        lines.append(
            f"| [{code_span(export_name)}](#{symbol_anchor}) "
            f"| {markdown_table_text(symbol['kind'])} | {markdown_table_text(symbol_summary(symbol))} |"
        )

    lines.append("")
    for export_name in module["exports"]:
        lines.extend(render_python_symbol(module_name, export_name, module["symbols"][export_name]))

    return "\n".join(lines)


def render_schema_identifiers(schema_identifiers: list[dict[str, Any]]) -> list[str]:
    lines = [
        "### Schema Identifiers",
        "",
        "| Name | Value | Exported |",
        "|------|-------|----------|",
    ]
    for schema_identifier in schema_identifiers:
        lines.append(
            f"| {markdown_table_text(code_span(schema_identifier['name']))} "
            f"| {markdown_table_text(code_span(str(schema_identifier['value'])))} "
            f"| {markdown_table_text(str(schema_identifier['public_exported']).lower())} |"
        )

    lines.append("")

    return lines


def render_python_symbol(module_name: str, export_name: str, symbol: dict[str, Any]) -> list[str]:
    lines = [
        f'<a id="{anchor_id("python-api-symbol-" + module_name + "-" + export_name)}"></a>',
        f"### {code_span(export_name)}",
        "",
        f"- Kind: {code_span(symbol['kind'])}",
    ]

    match symbol["kind"]:
        case "function":
            append_optional_field(lines, "Signature", symbol.get("signature"))
        case "contract_model":
            append_optional_field(lines, "Signature", symbol.get("signature"))
            append_sequence_field(lines, "Fields", symbol.get("field_names", []))
        case "enum":
            lines.extend(render_enum_members(symbol["members"]))
        case "class" | "exception_class":
            append_optional_field(lines, "Origin", symbol.get("origin_module"))
            append_optional_field(lines, "Qualified name", symbol.get("qualname"))
            append_sequence_field(lines, "Base classes", symbol.get("base_classes", []))
            append_optional_field(lines, "Constructor", symbol.get("constructor_signature"))

            if symbol.get("public_methods"):
                lines.extend(render_public_methods(symbol["public_methods"]))
        case "constant":
            lines.extend(render_constant_value(symbol.get("value")))
        case _:
            raise ValueError(f"Unsupported public API symbol kind: {symbol['kind']}")

    lines.append("")

    return lines


def render_enum_members(members: list[dict[str, Any]]) -> list[str]:
    lines = [
        "",
        "| Member | Value |",
        "|--------|-------|",
    ]
    for member in members:
        lines.append(
            f"| {markdown_table_text(code_span(member['name']))} "
            f"| {markdown_table_text(code_span(str(member['value'])))} |"
        )

    return lines


def render_public_methods(public_methods: dict[str, str]) -> list[str]:
    lines = [
        "",
        "| Method | Signature |",
        "|--------|-----------|",
    ]
    for method_name, signature in public_methods.items():
        lines.append(
            f"| {markdown_table_text(code_span(method_name))} "
            f"| {markdown_table_text(code_span(signature))} |"
        )

    return lines


def render_constant_value(value: Any) -> list[str]:
    if isinstance(value, str | int | float | bool) or value is None:
        return [f"- Value: {code_span(str(value))}"]

    value_json = json.dumps(value, indent=2, sort_keys=True)

    return [
        "- Value:",
        "",
        "```json",
        value_json,
        "```",
    ]


def symbol_summary(symbol: dict[str, Any]) -> str:
    match symbol["kind"]:
        case "function":
            return none_to_empty(symbol.get("signature"))
        case "contract_model":
            field_names = symbol.get("field_names", [])
            return f"{len(field_names)} fields"
        case "enum":
            members = symbol.get("members", [])
            return f"{len(members)} members"
        case "class" | "exception_class":
            return none_to_empty(symbol.get("origin_module"))
        case "constant":
            return "constant value"
        case _:
            return ""


def append_optional_field(lines: list[str], label: str, value: Any) -> None:
    if value is None:
        return

    lines.append(f"- {label}: {code_span(str(value))}")


def append_sequence_field(lines: list[str], label: str, values: list[str]) -> None:
    if not values:
        return

    rendered_values = ", ".join(code_span(value) for value in values)
    lines.append(f"- {label}: {rendered_values}")


def none_to_empty(value: Any) -> str:
    if value is None:
        return ""

    return str(value)


def code_span(value: str) -> str:
    delimiter = "`" if "`" not in value else "``"
    return f"{delimiter}{value}{delimiter}"


def markdown_table_text(value: str) -> str:
    return value.replace("\n", "<br>").replace("|", "\\|")


def anchor_id(value: str) -> str:
    characters: list[str] = []
    previous_was_separator = False

    for character in value.lower():
        if character.isalnum():
            characters.append(character)
            previous_was_separator = False

            continue

        if not previous_was_separator:
            characters.append("-")
            previous_was_separator = True

    return "".join(characters).strip("-")


if __name__ == "__main__":
    raise SystemExit(main())
