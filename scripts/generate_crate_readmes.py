import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import subprocess

GENERATED_HEADER = "<!-- This file is generated by scripts/generate_crate_readmes.py. DO NOT EDIT. -->"
REPOSITORY_URL = "https://github.com/lejmer/janiform"

ROOT_TEMPLATE = """{generated_header}

# {name}

{description}

This crate is the umbrella Rust facade for [Janiform]({repository_url}). The canonical user-facing
overview, Python package entry points, CLI examples, and workflow guidance live in the
[repository README]({repository_readme_url}).

This version is `{version}`. The source for this crate lives [here]({source_url}).

## Workspace Crates

{workspace_members}

Most Janiform workspace crates are internal implementation details and evolve together inside this
repository.
"""

INTERNAL_TEMPLATE = """{generated_header}

# {name}

{description}

This crate is an internal component of [Janiform]({repository_url}). Its Rust API may change as the
workspace evolves.

This version is `{version}`. The source for this crate lives [here]({source_url}).

The top-level project overview and workflow documentation live in the
[repository README]({repository_readme_url}).
"""

PYBIND_TEMPLATE = """{generated_header}

# {name}

{description}

This crate owns the PyO3 boundary for [Janiform]({repository_url}). It is a workspace integration
crate rather than a standalone Rust API.

This version is `{version}`. The source for this crate lives [here]({source_url}).

The public Python package and CLI are documented in the [repository README]({repository_readme_url}).
"""

UNPUBLISHED_TEMPLATE = """{generated_header}

# {name}

{description}

This crate is an internal workspace support crate for [Janiform]({repository_url}) and is not
published independently.

This version is `{version}`. The source for this crate lives [here]({source_url}).

The broader project overview and contributor-oriented workflow documentation live in the
[repository README]({repository_readme_url}).
"""


@dataclass(frozen=True)
class WorkspacePackage:
    manifest_path: Path
    name: str
    description: str
    version: str
    publish: bool

    @property
    def crate_directory(self) -> Path:
        return self.manifest_path.parent


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate or validate checked-in README.md files for workspace crates.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with a non-zero status when a generated README is out of date.",
    )
    args = parser.parse_args()

    workspace_root, packages = load_workspace_packages()
    expected_readmes = build_expected_readmes(workspace_root, packages)

    drifted_paths: list[Path] = []
    for path, expected_content in expected_readmes.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected_content:
                drifted_paths.append(path)
            continue

        path.write_text(expected_content, encoding="utf-8")

    if args.check:
        if drifted_paths:
            print("Generated crate README files are out of date:")
            for path in drifted_paths:
                print(f"- {path.relative_to(workspace_root)}")
            print("Regenerate them with `python3 scripts/generate_crate_readmes.py`.")
            return 1
        return 0

    print(f"Generated {len(expected_readmes)} crate README files.")
    return 0


def load_workspace_packages() -> tuple[Path, tuple[WorkspacePackage, ...]]:
    result = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--no-deps"],
        capture_output=True,
        check=True,
        text=True,
    )
    metadata = json.loads(result.stdout)
    workspace_root = Path(metadata["workspace_root"])
    workspace_member_ids = set(metadata["workspace_members"])

    packages: list[WorkspacePackage] = []
    for package in metadata["packages"]:
        package_id = package["id"]
        if package_id not in workspace_member_ids:
            continue

        description = package.get("description")
        if not isinstance(description, str) or not description.strip():
            raise ValueError(f"Workspace crate `{package['name']}` is missing a package description.")

        publish_field = package.get("publish")
        packages.append(
            WorkspacePackage(
                manifest_path=Path(package["manifest_path"]),
                name=package["name"],
                description=description.strip(),
                version=package["version"],
                publish=publish_field is not False and publish_field != [],
            )
        )

    packages.sort(key=lambda package: package.name)
    return workspace_root, tuple(packages)


def build_expected_readmes(
    workspace_root: Path,
    packages: tuple[WorkspacePackage, ...],
) -> dict[Path, str]:
    if not any(package.name == "janiform" for package in packages):
        raise ValueError("Workspace crate `janiform` was not found in cargo metadata output.")

    readmes: dict[Path, str] = {}
    for package in packages:
        readmes[package.crate_directory / "README.md"] = render_readme(
            workspace_root=workspace_root,
            package=package,
            packages=packages,
        )

    return readmes


def render_readme(
    workspace_root: Path,
    package: WorkspacePackage,
    packages: tuple[WorkspacePackage, ...],
) -> str:
    template = select_template(package)
    workspace_members = render_workspace_members(workspace_root, packages)
    repository_readme_url = f"{REPOSITORY_URL}/blob/main/README.md"
    source_url = f"{REPOSITORY_URL}/blob/main/{package.crate_directory.relative_to(workspace_root).as_posix()}"

    return template.format(
        description=package.description,
        generated_header=GENERATED_HEADER,
        name=package.name,
        repository_readme_url=repository_readme_url,
        repository_url=REPOSITORY_URL,
        source_url=source_url,
        version=package.version,
        workspace_members=workspace_members,
    )


def select_template(package: WorkspacePackage) -> str:
    if package.name == "janiform":
        return ROOT_TEMPLATE
    if package.name == "janiform-pybind":
        return PYBIND_TEMPLATE
    if not package.publish:
        return UNPUBLISHED_TEMPLATE
    return INTERNAL_TEMPLATE


def render_workspace_members(
    workspace_root: Path,
    packages: tuple[WorkspacePackage, ...],
) -> str:
    lines: list[str] = []
    for package in packages:
        if package.name == "janiform":
            continue
        crate_path = package.crate_directory.relative_to(workspace_root).as_posix()
        source_url = f"{REPOSITORY_URL}/blob/main/{crate_path}"
        unpublished_suffix = " Not published independently." if not package.publish else ""
        lines.append(f"- [{package.name}]({source_url}): {package.description}{unpublished_suffix}")
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
